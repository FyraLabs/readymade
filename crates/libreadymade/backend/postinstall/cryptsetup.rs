use super::{Context, PostInstallModule};
use crate::{backend::mounts::generate_cryptdata, prelude::*};

/// Write `/etc/crypttab` for the encrypted partitions of the installation.
///
/// This should run before the initramfs is regenerated (e.g. [`super::reinstall_kernel::ReinstallKernel`] or
/// [`super::dracut::Dracut`]), so that it is included in the initramfs.
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
pub struct CryptSetup;

impl PostInstallModule for CryptSetup {
    fn name(&self) -> &'static str {
        "CryptSetup"
    }

    fn run(&self, context: &Context) -> Result<()> {
        let Some(crypt_data) = generate_cryptdata(&context.mounts)? else {
            tracing::debug!("No encrypted partitions, not writing /etc/crypttab");
            return Ok(());
        };

        tracing::info!("Writing /etc/crypttab...");
        std::fs::create_dir_all("/etc").wrap_err("cannot create /etc/")?;
        std::fs::write(
            "/etc/crypttab",
            format!(
                "# This file is generated by Readymade.\n{}",
                crypt_data.crypttab
            ),
        )
        .wrap_err("cannot write to /etc/crypttab")?;

        Ok(())
    }
}
